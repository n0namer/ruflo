import { generateKeyPairSync, sign } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { createPinnedQaAuthenticator } from '../../src/missions/native-qa-attestation.js';
import { INDEPENDENT_QA_SCHEMA } from '../../src/missions/execution-quality.js';

const digest = (c: string) => 'sha256:' + c.repeat(64);
const base = () => ({
  principalId: 'qa-reviewer-dedicated',
  authenticatedReceiptId: 'receipt-external-1',
  receipt: {
    schema: INDEPENDENT_QA_SCHEMA,
    receiptId: 'receipt-external-1',
    missionId: 'msn_aaaaaaaaaaaaaaaaaaaaaaaa',
    executionId: 'inv-1',
    planRevision: 3,
    criteriaDigest: digest('a'),
    artifactDigest: digest('b'),
    verdict: 'passed' as const,
    producer: {kind:'independent-qa' as const,qaRunId:'qa-review-process-123'},
    evidenceRef: 'sha-proof-123',
    issuedAt: '2026-10-20T00:01:00.000Z',
  },
});
const canonical = (record:ReturnType<typeof base>) => JSON.stringify([
  'ruflo.m2.qa-attestation/v1', record.principalId, record.authenticatedReceiptId,
  record.receipt.schema,record.receipt.receiptId,record.receipt.missionId,
  record.receipt.executionId,record.receipt.planRevision,record.receipt.criteriaDigest,
  record.receipt.artifactDigest,record.receipt.verdict,record.receipt.producer.kind,
  record.receipt.producer.qaRunId,record.receipt.evidenceRef,record.receipt.issuedAt,
]);
function fixture() {
  const { privateKey, publicKey } = generateKeyPairSync('ed25519');
  const now = Date.parse('2026-10-20T00:03:00.000Z');
  const pem = publicKey.export({type:'spki',format:'pem'}).toString();
  const authenticator = createPinnedQaAuthenticator({
    publicKeyPem:pem,reviewerPrincipalId:'qa-reviewer-dedicated',
    now:()=>now,maxReceiptAgeMs:600_000,
  });
  const rec = base();
  const signatureBase64 = sign(null,Buffer.from(canonical(rec)),privateKey).toString('base64');
  return { authenticator, record:{...rec,signatureBase64}, pem,now };
}
describe('externally issued Ed25519 QA receipt verifier',()=>{
  it('verifies a signed external reviewer result bound to mission, invocation and SHA',async()=>{
    const x=fixture();
    expect(await x.authenticator(x.record,x.record.receipt.missionId,'inv-1')).toBe(true);
  });
  it('does not accept unsigned or malformed reviewer claims',async()=>{
    const x=fixture();
    expect(await x.authenticator({...x.record,signatureBase64:''} as any,x.record.receipt.missionId,'inv-1')).toBe(false);
    expect(await x.authenticator({...x.record,signatureBase64:'=='},x.record.receipt.missionId,'inv-1')).toBe(false);
  });
  it('rejects artifact, acceptance criteria, plan revision and verdict tampering',async()=>{
    const x=fixture();
    for (const receipt of [
      {...x.record.receipt,artifactDigest:digest('c')},
      {...x.record.receipt,criteriaDigest:digest('d')},
      {...x.record.receipt,planRevision:4},
      {...x.record.receipt,verdict:'failed' as const},
      {...x.record.receipt,producer:{...x.record.receipt.producer,qaRunId:'foreign-review'}},
    ]) {
      expect(await x.authenticator({...x.record,receipt} as any,x.record.receipt.missionId,'inv-1')).toBe(false);
    }
  });
  it('rejects unsigned identity substitution and mission/invocation replay',async()=>{
    const x=fixture();
    expect(await x.authenticator({...x.record,principalId:'attacker'},x.record.receipt.missionId,'inv-1')).toBe(false);
    expect(await x.authenticator(x.record,'msn_bbbbbbbbbbbbbbbbbbbbbbbb','inv-1')).toBe(false);
    expect(await x.authenticator(x.record,x.record.receipt.missionId,'inv-2')).toBe(false);
    expect(await x.authenticator({...x.record,authenticatedReceiptId:'receipt-fake'},x.record.receipt.missionId,'inv-1')).toBe(false);
  });
  it('rejects a valid signed receipt generated by a non-pinned key',async()=>{
    const x=fixture();
    const attack = generateKeyPairSync('ed25519');
    const signatureBase64=sign(null,Buffer.from(canonical(base())),attack.privateKey).toString('base64');
    expect(await x.authenticator({...x.record,signatureBase64},x.record.receipt.missionId,'inv-1')).toBe(false);
  });
  it('rejects stale/future issued receipts even if signed',async()=>{
    const x=fixture();
    const old = createPinnedQaAuthenticator({
      publicKeyPem:x.pem,reviewerPrincipalId:'qa-reviewer-dedicated',
      now:()=>x.now+700_000,maxReceiptAgeMs:600_000,
    });
    const future = createPinnedQaAuthenticator({
      publicKeyPem:x.pem,reviewerPrincipalId:'qa-reviewer-dedicated',
      now:()=>x.now-160_000,
    });
    expect(await old(x.record,x.record.receipt.missionId,'inv-1')).toBe(false);
    expect(await future(x.record,x.record.receipt.missionId,'inv-1')).toBe(false);
  });
  it('fails closed for invalid key type or unreadable trust root',()=>{
    const wrong = generateKeyPairSync('rsa',{modulusLength:2048});
    expect(()=>createPinnedQaAuthenticator({publicKeyPem:wrong.publicKey.export({format:'pem',type:'spki'}).toString(),
      reviewerPrincipalId:'qa-reviewer-dedicated'})).toThrow('Ed25519');
    expect(()=>createPinnedQaAuthenticator({publicKeyPem:'BAD KEY',
      reviewerPrincipalId:'qa-reviewer-dedicated'})).toThrow();
  });
});
